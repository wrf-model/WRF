! Independent physical-invariant checks for the production green-roof column.
! Synthetic materials and boundary conditions, not a calibrated roof assembly.
PROGRAM greenroof_column_invariants
  USE module_sf_greenroof_bem, ONLY: greenroof_column_step, greenroof_bem_diagnostics
  USE, INTRINSIC :: ieee_arithmetic, ONLY: ieee_is_finite
  IMPLICIT NONE
  REAL(KIND=8), PARAMETER :: dz(4)=[0.05_8,0.10_8,0.15_8,0.20_8]
  REAL(KIND=8), PARAMETER :: cap(4)=[2.1E6_8,1.9E6_8,2.3E6_8,1.0E6_8]
  REAL(KIND=8), PARAMETER :: cond(4)=[0.30_8,0.50_8,0.80_8,0.67_8]
  REAL(KIND=8) :: old(4),new(4),expected(4),plus(4),minus(4)
  REAL(KIND=8) :: t120(4),t60(4),t30(4),derivative,dummy,ts,tin,hc,hr,dt
  REAL(KIND=8) :: qsteady,resistance,resistance_above,q(0:4),local_error(4)
  REAL(KIND=8) :: energy_error,finite_difference,derivative_error,coarse,fine,ratio
  TYPE(greenroof_bem_diagnostics) :: diag,dp,dm
  INTEGER :: k

  ! No heat is generated by an isothermal passive column.
  old=300.0_8
  CALL greenroof_column_step(120.0_8,dz,cap,cond,old,300.0_8,300.0_8,3.0_8,5.0_8,new,diag,derivative)
  CALL require(MAXVAL(ABS(new-old)) < 1.0E-10_8,'isothermal temperatures')
  CALL require(ABS(diag%surface_to_column_wm2) < 1.0E-8_8,'isothermal top flux')
  CALL require(ABS(diag%roof_to_indoor_wm2) < 1.0E-8_8,'isothermal room flux')
  WRITE(*,'(A)') 'ISOTHERMAL_PASS'

  ! The exact stationary solution follows resistances in series. This
  ! checks unequal cell thickness/conductivity and the bottom half cell.
  ts=310.0_8; tin=290.0_8; hc=3.0_8; hr=5.0_8
  resistance=SUM(dz/cond)+1.0_8/(hc+hr)
  qsteady=(ts-tin)/resistance
  resistance_above=0.0_8
  DO k=1,4
    expected(k)=ts-qsteady*(resistance_above+0.5_8*dz(k)/cond(k))
    resistance_above=resistance_above+dz(k)/cond(k)
  END DO
  CALL greenroof_column_step(1800.0_8,dz,cap,cond,expected,ts,tin,hc,hr,new,diag,derivative)
  CALL require(MAXVAL(ABS(new-expected)) < 1.0E-10_8,'stationary layer temperatures')
  CALL require(ABS(diag%surface_to_column_wm2-qsteady) < 1.0E-8_8,'stationary top resistance')
  CALL require(ABS(diag%roof_to_indoor_wm2-qsteady) < 1.0E-8_8,'stationary total resistance')
  CALL require(MAXVAL(ABS(diag%layer_interface_wm2-qsteady)) < 1.0E-8_8,'stationary interface continuity')
  CALL require(ABS(diag%inner_surface_k-(tin+qsteady/(hc+hr))) < 1.0E-10_8,'inner surface resistance')
  WRITE(*,'(A,ES24.16E3)') 'STEADY_HEAT_FLUX_WM2=',qsteady
  WRITE(*,'(A)') 'STEADY_RESISTANCE_PASS'

  ! Reconstruct the fluxes from the new layer temperatures and physical
  ! resistances, independently of the returned diagnostic balance field.
  old=[302.0_8,300.0_8,298.0_8,296.0_8]
  ts=310.0_8; tin=294.0_8; hc=3.2_8; hr=5.1_8; dt=60.0_8
  CALL greenroof_column_step(dt,dz,cap,cond,old,ts,tin,hc,hr,new,diag,derivative)
  q(0)=(ts-new(1))/(0.5_8*dz(1)/cond(1))
  DO k=1,3
    q(k)=(new(k)-new(k+1))/(0.5_8*dz(k)/cond(k)+0.5_8*dz(k+1)/cond(k+1))
  END DO
  q(4)=(new(4)-tin)/(0.5_8*dz(4)/cond(4)+1.0_8/(hc+hr))
  DO k=1,4
    local_error(k)=cap(k)*dz(k)*(new(k)-old(k))/dt-(q(k-1)-q(k))
  END DO
  energy_error=SUM(cap*dz*(new-old))/dt-(q(0)-q(4))
  CALL require(MAXVAL(ABS(local_error)) < 2.0E-8_8,'transient cell energy conservation')
  CALL require(ABS(energy_error) < 2.0E-8_8,'transient total energy conservation')
  CALL require(ABS(diag%roof_conv_wm2+diag%roof_rad_wm2-q(4)) < 1.0E-10_8,'same room heat passed to BEM')
  CALL require(ABS(diag%roof_conv_wm2-hc*(diag%inner_surface_k-tin)) < 1.0E-9_8,'convective room split')
  CALL require(ABS(diag%roof_rad_wm2-hr*(diag%inner_surface_k-tin)) < 1.0E-9_8,'radiative room split')
  WRITE(*,'(A,ES24.16E3)') 'MAX_CELL_RESIDUAL_WM2=',MAXVAL(ABS(local_error))
  WRITE(*,'(A,ES24.16E3)') 'TOTAL_ENERGY_RESIDUAL_WM2=',ABS(energy_error)
  WRITE(*,'(A)') 'TRANSIENT_CONSERVATION_PASS'

  ! Check the Newton derivative against fresh solves from the identical
  ! old state; perturbing a previously advanced state would test the wrong map.
  CALL greenroof_column_step(dt,dz,cap,cond,old,ts+1.0E-3_8,tin,hc,hr,plus,dp,dummy)
  CALL greenroof_column_step(dt,dz,cap,cond,old,ts-1.0E-3_8,tin,hc,hr,minus,dm,dummy)
  finite_difference=(dp%surface_to_column_wm2-dm%surface_to_column_wm2)/2.0E-3_8
  derivative_error=ABS(derivative-finite_difference)
  CALL require(derivative_error < 1.0E-7_8,'surface response derivative')
  CALL require(derivative > 0.0_8 .AND. derivative < 2.0_8*cond(1)/dz(1),'passive surface derivative')
  WRITE(*,'(A,ES24.16E3)') 'DERIVATIVE_ABS_ERROR_WM2K=',derivative_error
  WRITE(*,'(A)') 'SURFACE_DERIVATIVE_PASS'

  ! At one common physical time, first-order time discretization should
  ! reduce the solution difference as dt is halved. No source-code formula
  ! is duplicated in this refinement experiment.
  CALL integrate(120.0_8,t120)
  CALL integrate(60.0_8,t60)
  CALL integrate(30.0_8,t30)
  coarse=MAXVAL(ABS(t120-t60))
  fine=MAXVAL(ABS(t60-t30))
  CALL require(coarse > 1.0E-7_8,'refinement signal must exceed roundoff')
  ratio=fine/coarse
  CALL require(ratio > 0.25_8 .AND. ratio < 0.75_8,'first-order time refinement')
  WRITE(*,'(A,ES24.16E3)') 'DT120_MINUS_DT60_MAX_K=',coarse
  WRITE(*,'(A,ES24.16E3)') 'DT60_MINUS_DT30_MAX_K=',fine
  WRITE(*,'(A,ES24.16E3)') 'REFINEMENT_RATIO=',ratio
  WRITE(*,'(A)') 'TIME_REFINEMENT_PASS'
  WRITE(*,'(A)') 'GREENROOF_COLUMN_NATIVE_PASS'

CONTAINS
  SUBROUTINE require(ok,message)
    LOGICAL,INTENT(IN) :: ok
    CHARACTER(LEN=*),INTENT(IN) :: message
    IF (.NOT.ok) THEN
      WRITE(*,'(A)') 'GREENROOF_COLUMN_FAIL: '//message
      ERROR STOP 1
    END IF
  END SUBROUTINE require

  SUBROUTINE integrate(step,temperature)
    REAL(KIND=8),INTENT(IN) :: step
    REAL(KIND=8),INTENT(OUT) :: temperature(4)
    REAL(KIND=8) :: previous(4),slope
    TYPE(greenroof_bem_diagnostics) :: state_diag
    INTEGER :: iteration
    temperature=[302.0_8,300.0_8,298.0_8,296.0_8]
    DO iteration=1,NINT(7200.0_8/step)
      previous=temperature
      CALL greenroof_column_step(step,dz,cap,cond,previous,310.0_8,294.0_8,3.2_8,5.1_8, &
                                 temperature,state_diag,slope)
      CALL require(ALL(ieee_is_finite(temperature)),'finite refinement temperatures')
    END DO
  END SUBROUTINE integrate
END PROGRAM greenroof_column_invariants
